-- Productos terminados: el catálogo de los estándar.
--
-- Un producto terminado es lo que el taller fabrica: una caja, un ánfora, un
-- display. Los estándar tienen forma fija y cambian de medida, material,
-- espesor y opciones; lo que tenga otra forma es "personalizado" y se llena a
-- mano en el pedido, sin pasar por aquí.
--
--   pt_tipos       Caja, Ánfora, Display… con el factor de fabricación del precio
--   pt_productos   cada producto estándar, con la forma en que se estima su material
--   pt_medidas     sus medidas estándar (cm)
--   pt_espesores   sus espesores recomendados (mm)
--   pt_colores     colores de acrílico, y cuáles admite cada producto
--   pt_opciones    personalizaciones, acabados y complementos, cada una con el
--                  monto que suma al precio, y cuáles admite cada producto
--   pt_materiales  de qué está hecho cada componente (informativo)
--   pt_segmentos   a qué mercado apunta (informativo)
--
-- Los datos vienen del Excel de la empresa (`supabase/seeds/productos_terminados.xlsx`)
-- y están en la migración siguiente, que genera `scripts/gen-terminados.mjs`.
-- A partir de ahí se mantiene desde /configuracion.

-- Cómo se estima cuánta plancha lleva un producto a partir de sus medidas.
create type public.pt_geometria as enum (
  'caja_cerrada',    -- seis caras: medida 1 × 2 × 3
  'caja_abierta',    -- cinco caras: sin la de arriba
  'cilindro',        -- pared y dos tapas: diámetro × altura
  'lamina',          -- una cara: medida 1 × 2
  'lamina_plegada',  -- una lámina doblada: medida 1 × (medida 2 + medida 3)
  'letras',          -- por letra: altura × un ancho proporcional
  'manual'           -- no se calcula: el área la escribe quien cotiza
);

create type public.pt_clase_opcion as enum ('personalizacion', 'acabado', 'complemento');

create table public.pt_tipos (
  codigo text primary key check (codigo ~ '^[A-Z]{2,5}$'),
  nombre text not null unique check (btrim(nombre) <> ''),
  orden  smallint not null default 0,
  -- Por cuánto se multiplica el costo del material para llegar al precio.
  factor_fabricacion numeric(8, 3) not null default 1 check (factor_fabricacion > 0)
);

create table public.pt_productos (
  codigo text primary key check (codigo ~ '^[A-Z]{2,5}-[0-9]{3,}$'),
  codigo_original text,
  tipo   text not null references public.pt_tipos (codigo) on update cascade,
  nombre text not null check (btrim(nombre) <> ''),
  usos   text,
  -- Se fabrica a medida: las medidas listadas son solo una referencia.
  a_medida boolean not null default false,
  contacto_alimentario text,
  imagen_url text,
  notas  text,
  geometria public.pt_geometria not null default 'manual',
  activo boolean not null default true,
  actualizado_en timestamptz not null default now()
);

create index pt_productos_tipo_idx on public.pt_productos (tipo);

create trigger pt_productos_actualizado_en
  before update on public.pt_productos
  for each row execute function public.tocar_actualizado_en();

create table public.pt_medidas (
  id uuid primary key default gen_random_uuid(),
  producto text not null references public.pt_productos (codigo) on update cascade on delete cascade,
  orden smallint not null default 1,
  -- En el orden en que la empresa las escribe; los cilindros usan diámetro y
  -- altura, las letras solo altura (con un máximo si es un rango).
  medida_1_cm   numeric(7, 2) check (medida_1_cm > 0),
  medida_2_cm   numeric(7, 2) check (medida_2_cm > 0),
  medida_3_cm   numeric(7, 2) check (medida_3_cm > 0),
  diametro_cm   numeric(7, 2) check (diametro_cm > 0),
  altura_cm     numeric(7, 2) check (altura_cm > 0),
  altura_max_cm numeric(7, 2) check (altura_max_cm > 0),
  -- "A4", "A3"… cuando la medida es la de un formato de papel.
  formato  text,
  estimado boolean not null default false,
  nota     text,
  check (coalesce(medida_1_cm, diametro_cm, altura_cm) is not null)
);

create index pt_medidas_producto_idx on public.pt_medidas (producto, orden);

create table public.pt_espesores (
  id uuid primary key default gen_random_uuid(),
  producto text not null references public.pt_productos (codigo) on update cascade on delete cascade,
  orden smallint not null default 1,
  espesor_min_mm numeric(5, 2) not null check (espesor_min_mm > 0),
  espesor_max_mm numeric(5, 2) not null check (espesor_max_mm >= espesor_min_mm),
  -- "Pequeña", "Base", "A4"… para qué tamaño o parte se recomienda.
  aplicacion text,
  material   text,
  estimado   boolean not null default false,
  nota       text
);

create index pt_espesores_producto_idx on public.pt_espesores (producto, orden);

create table public.pt_colores (
  id integer generated by default as identity primary key,
  nombre text not null unique check (btrim(nombre) <> '')
);

create table public.pt_producto_color (
  producto text not null references public.pt_productos (codigo) on update cascade on delete cascade,
  color_id integer not null references public.pt_colores (id) on delete cascade,
  primary key (producto, color_id)
);

create table public.pt_opciones (
  id integer generated by default as identity primary key,
  clase  public.pt_clase_opcion not null,
  nombre text not null check (btrim(nombre) <> ''),
  -- Lo que suma al precio de cada unidad cuando se elige.
  extra  numeric(12, 2) not null default 0 check (extra >= 0),
  unique (clase, nombre)
);

create table public.pt_producto_opcion (
  producto  text not null references public.pt_productos (codigo) on update cascade on delete cascade,
  opcion_id integer not null references public.pt_opciones (id) on delete cascade,
  -- Un complemento que el producto trae siempre no es opcional: viene marcado.
  opcional  boolean not null default true,
  detalle   text,
  primary key (producto, opcion_id)
);

create table public.pt_materiales (
  id integer generated by default as identity primary key,
  nombre    text not null unique check (btrim(nombre) <> ''),
  categoria text
);

create table public.pt_producto_material (
  id uuid primary key default gen_random_uuid(),
  producto    text not null references public.pt_productos (codigo) on update cascade on delete cascade,
  material_id integer not null references public.pt_materiales (id) on delete cascade,
  componente  text,
  opcional    boolean not null default false,
  especificacion text
);

create index pt_producto_material_producto_idx on public.pt_producto_material (producto);

create table public.pt_segmentos (
  id integer generated by default as identity primary key,
  nombre text not null unique check (btrim(nombre) <> ''),
  sector text
);

create table public.pt_producto_segmento (
  producto    text not null references public.pt_productos (codigo) on update cascade on delete cascade,
  segmento_id integer not null references public.pt_segmentos (id) on delete cascade,
  primary key (producto, segmento_id)
);

-- ── Permisos ────────────────────────────────────────────────────────────────
-- Como el catálogo de planchas: cotizar es de Administración, y con ello el
-- catálogo y sus precios. El taller ve el producto ya armado, en el pedido.

do $$
declare
  t text;
begin
  foreach t in array array[
    'pt_tipos', 'pt_productos', 'pt_medidas', 'pt_espesores', 'pt_colores', 'pt_producto_color',
    'pt_opciones', 'pt_producto_opcion', 'pt_materiales', 'pt_producto_material',
    'pt_segmentos', 'pt_producto_segmento'
  ] loop
    execute format('alter table public.%I enable row level security', t);
    execute format(
      'create policy %I on public.%I for all to authenticated using (public.es_admin()) with check (public.es_admin())',
      t || '_admin', t
    );
    execute format('revoke all on public.%I from anon, authenticated', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;

